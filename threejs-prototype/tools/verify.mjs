import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';

const browser = await chromium.launch({ headless: true, channel: 'chrome', args: ['--enable-webgl', '--ignore-gpu-blocklist', '--use-angle=d3d11'] });
const errors = [], checks = [];
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); };
await mkdir('artifacts', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const response = await page.goto('http://127.0.0.1:5174/?capture=1', { waitUntil: 'networkidle' });
  check('Preview HTTP 200', response.status() === 200);
  await page.waitForFunction(() => window.__flightTest?.ready);
  await page.waitForTimeout(800);
  let state = await page.evaluate(() => window.__flightTest.state);
  check('Default loaded Gripen pilot view with calibrated seat', state.model === 'gripen' && state.view === 'pilot' && state.seat[1] === .65 && state.paused);
  check('Default mode targets 120 FPS with adaptive resolution', state.quality === 'performance' && state.performance.targetFPS === 120 && state.performance.adaptive);
  const defaultBanks = state.worldQuality.activeCloudBanks;
  await page.locator('#settings-toggle').click();
  check('Scene controls open', await page.locator('#settings').isVisible());
  await page.locator('#quality').selectOption('high');
  state = await page.evaluate(() => window.__flightTest.state);
  check('High restores detail without deleting cloud banks', state.worldQuality.cloudRaySteps === 80 && state.worldQuality.terrainTriangles === 524288 && state.worldQuality.activeCloudBanks === defaultBanks && !state.performance.adaptive);
  await page.locator('#quality').selectOption('performance');
  state = await page.evaluate(() => window.__flightTest.state);
  check('Performance reduces work while preserving cloud cover', state.worldQuality.cloudRaySteps === 28 && state.worldQuality.terrainTriangles === 131072 && state.worldQuality.activeCloudBanks === defaultBanks);
  await page.locator('#fov').evaluate(input => { input.value = '76'; input.dispatchEvent(new Event('input', { bubbles: true })); });
  check('FOV control changes camera projection', await page.evaluate(() => window.__flightTest.state.fov) === 76);
  await page.locator('#exposure').evaluate(input => { input.value = '110'; input.dispatchEvent(new Event('input', { bubbles: true })); });
  check('Exposure control updates renderer', await page.evaluate(() => window.__flightTest.state.exposure) === 1.1);
  const cloudCalls = await page.evaluate(() => window.__flightTest.state.renderer.calls);
  await page.locator('#cloud-cover').evaluate(input => { input.value = '0'; input.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.waitForTimeout(250);
  check('Zero cloud cover removes cloud draw calls', await page.evaluate(() => window.__flightTest.state.renderer.calls) < cloudCalls);
  await page.locator('#cloud-cover').evaluate(input => { input.value = '65'; input.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.locator('#quality').selectOption('balanced');
  check('Quality control selects balanced rendering', await page.evaluate(() => window.__flightTest.state.quality) === 'balanced');
  await page.locator('#preset').selectOption('clouds');
  check('Cloud preset changes flight altitude', await page.evaluate(() => window.__flightTest.state.position[1]) === 3700);
  await page.locator('#preset').selectOption('daylight');
  check('Daylight preset returns to coast altitude', await page.evaluate(() => window.__flightTest.state.preset === 'daylight' && window.__flightTest.state.position[1] === 1800));
  await page.locator('#close-settings').click();
  await page.locator('#chase-view').click();
  check('Exterior camera switches', await page.evaluate(() => window.__flightTest.state.view) === 'chase');
  await page.screenshot({ path: 'artifacts/exterior.png' });
  await page.locator('#pilot-view').click();
  await page.mouse.move(850, 350); await page.mouse.down(); await page.mouse.move(970, 410); await page.mouse.up();
  check('Drag changes pilot look direction', await page.evaluate(() => Math.abs(window.__flightTest.state.look[0]) > .1));
  await page.locator('#flight').dblclick({ position: { x: 850, y: 350 } });
  check('Double click centres pilot look', await page.evaluate(() => window.__flightTest.state.look.every(value => value === 0)));
  await page.locator('#pause').click();
  const before = await page.evaluate(() => window.__flightTest.state.position[2]);
  await page.waitForTimeout(400);
  check('Running flight advances position', await page.evaluate(() => window.__flightTest.state.position[2]) < before - 5);
  await page.keyboard.press('ArrowLeft');
  await page.keyboard.press('KeyR');
  check('Reset restores initial flight position', await page.evaluate(() => Math.abs(window.__flightTest.state.position[0]) < .1 && Math.abs(window.__flightTest.state.position[2] - 3000) < 10));
  await page.keyboard.press('KeyH');
  check('Clean view hides overlay', await page.locator('body').evaluate(body => body.classList.contains('ui-hidden')));
  await page.keyboard.press('KeyH');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(300);
  check('Mobile canvas fits viewport', await page.locator('#flight').evaluate(canvas => Math.abs(canvas.getBoundingClientRect().width - 390) < 1));
  check('Mobile toolbar fits viewport', await page.locator('.toolbar').evaluate(node => { const r = node.getBoundingClientRect(); return r.left >= 0 && r.right <= 390; }));
  await page.screenshot({ path: 'artifacts/mobile.png' });
  await page.goto('http://127.0.0.1:5174/?capture=1&model=eurofighter', { waitUntil: 'networkidle' });
  await page.waitForFunction(() => window.__flightTest?.ready);
  check('Alternate Eurofighter model loads', await page.evaluate(() => window.__flightTest.state.model) === 'eurofighter');
  await page.waitForTimeout(250);
  check('No browser runtime or shader errors', errors.length === 0);
  await writeFile('artifacts/verification.json', JSON.stringify({ checks, errors, browser: await browser.version() }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
} finally { await browser.close(); }
